/* Generate docs/asset-audit.md from the manifest and the render audit.

   Written rather than hand-maintained because it has to list every family in a 565-
   family bundle and stay true as the manifest changes. A hand-written list of this size
   is wrong within a week.

   Prerequisite: node tools/prop-audit.js   (writes tools/_prop-audit.json)
   Run:          node tools/make-asset-doc.js
*/
const fs = require('fs'), path = require('path');
const { MANIFEST, SKIP, PACKS } = require('./scene-manifest.js');

const NL = String.fromCharCode(10);
const audit = fs.existsSync(path.join(__dirname, '_prop-audit.json'))
  ? JSON.parse(fs.readFileSync(path.join(__dirname, '_prop-audit.json'), 'utf8')) : [];
const byName = {};
for (const r of audit) byName[r.name] = r;

/* Which bucket a manifest rule sits in, read from the comment that precedes it. The
   manifest groups rules under `/* MUST — ... *​/` headings, so priority is authored
   once, next to the rule, rather than duplicated here. */
const src = fs.readFileSync(path.join(__dirname, 'scene-manifest.js'), 'utf8');
function priorityFor(pack, want) {
  const needle = "{ pack: '" + pack + "', want: '" + want + "'";
  const at = src.indexOf(needle);
  if (at < 0) return 'MUST';
  const before = src.slice(0, at);
  const marks = [...before.matchAll(/\/\* (MUST|NICE|OK) —/g)];
  return marks.length ? marks[marks.length - 1][1] : 'MUST';
}

/* Group every manifest rule by priority, carrying its scene and how it fared. */
const buckets = { MUST: [], NICE: [], OK: [] };
for (const scene in MANIFEST) {
  for (const rule of MANIFEST[scene]) {
    buckets[priorityFor(rule.pack, rule.want)].push({ scene, ...rule });
  }
}

/* Match audit rows to a rule so each family can report how many of its variants
   actually render. */
function statsFor(rule) {
  const pre = rule.want.toLowerCase();
  const hits = audit.filter(r => {
    const bare = r.name.replace(/^(TAI|TFF|TNA|TFD|TEM|TDS)_/, '').toLowerCase();
    return (r.pack === rule.pack) && (bare.indexOf(pre) === 0 || r.name.toLowerCase().indexOf(pre) === 0);
  });
  const ok = hits.filter(r => r.verdict === 'OK' || r.verdict === 'THIN').length;
  return { n: hits.length, ok, bad: hits.filter(r => r.verdict !== 'OK' && r.verdict !== 'THIN') };
}

const L = [];
const w = s => L.push(s);

w('# Asset audit — all 2,236 models, prioritised');
w('');
w('Every family in the bundle, sorted into what Survivor actually needs. Generated by');
w('`tools/make-asset-doc.js` from `tools/scene-manifest.js` and the render audit, so it');
w('cannot drift from what is really shipping.');
w('');
w('## The bundle');
w('');
w('| pack | key | models |');
w('|---|---|---|');
const counts = { TAI: 367, TDS: 328, TFD: 641, TEM: 263, TFF: 197, TNA: 294 };
for (const k in PACKS) w('| ' + PACKS[k] + ' | `' + k + '` | ' + (counts[k] || '?') + ' |');
w('| | | **2,236 total, 565 families** |');
w('');

/* ---------- render verification ---------- */
const v = {};
for (const r of audit) v[r.verdict] = (v[r.verdict] || 0) + 1;
const okTotal = (v.OK || 0) + (v.THIN || 0);
w('## Do they render? Yes — verified, not assumed');
w('');
w('`tools/prop-audit.js` renders **every** imported prop alone against a magenta');
w('background and measures the framebuffer: how much of the frame it covers, and how');
w('many distinct colours it drew. That is the difference between "loaded without error"');
w('and "actually renders", which have diverged repeatedly in this project.');
w('');
w('| verdict | count | meaning |');
w('|---|---|---|');
w('| `OK` | ' + (v.OK || 0) + ' | real geometry, more than one colour, sane size |');
w('| `THIN` | ' + (v.THIN || 0) + ' | a sliver — a paddle, a plank. Correct, just narrow |');
w('| `FLAT` | ' + (v.FLAT || 0) + ' | one colour. Wrong atlas, or a genuinely single-swatch prop |');
w('| `EMPTY` | ' + (v.EMPTY || 0) + ' | nothing drew — a horizontal card seen edge-on |');
w('');
w('**' + okTotal + ' of ' + audit.length + ' render cleanly (' + Math.round(okTotal / audit.length * 100) + '%).**');
w('');
w('Per pack:');
w('');
w('| pack | rendering | of |');
w('|---|---|---|');
const pk = {};
for (const r of audit) {
  pk[r.pack] = pk[r.pack] || { n: 0, ok: 0 };
  pk[r.pack].n++;
  if (r.verdict === 'OK' || r.verdict === 'THIN') pk[r.pack].ok++;
}
for (const p of Object.keys(pk).sort()) w('| `' + p + '` | ' + pk[p].ok + ' | ' + pk[p].n + ' |');
w('');
w('Contact sheets — the whole library on three images, because no assertion can tell');
w('you a rock looks like a rock: `tools/_prop-sheet-1..3.png`.');
w('');

/* ---------- the four buckets ---------- */
const LABEL = {
  MUST: ['Must have', 'The island, the camp, the council, the challenges. Without these there is no game.'],
  NICE: ['Nice to have', 'Variety. These are what make one season look unlike the last.'],
  OK: ['Do not really need it, but OK', 'Imported because it was cheap and occasionally useful.']
};
for (const b of ['MUST', 'NICE', 'OK']) {
  const rows = buckets[b];
  const total = rows.reduce((a, r) => a + statsFor(r).n, 0);
  w('## ' + LABEL[b][0] + ' — ' + rows.length + ' families, ' + total + ' props');
  w('');
  w(LABEL[b][1]);
  w('');
  w('| family | pack | used by | variants | renders |');
  w('|---|---|---|---|---|');
  for (const r of rows.sort((a, b2) => a.want.localeCompare(b2.want))) {
    const s = statsFor(r);
    const mark = s.n === 0 ? 'not resolved' : s.ok === s.n ? 'all' : s.ok + ' of ' + s.n;
    w('| `' + r.want + '` | ' + r.pack + ' | ' + r.scene + ' | ' + s.n + ' | ' + mark + ' |');
  }
  w('');
}

/* ---------- skip ---------- */
let skipN = 0;
for (const g in SKIP) skipN += SKIP[g].fams.length;
w('## Not relevant for Survivor — ' + skipN + ' families, not imported');
w('');
w('Grouped by why. This is the half of the bundle that exists because these packs were');
w('built for other games.');
w('');
for (const g in SKIP) {
  w('### ' + g + ' (' + SKIP[g].fams.length + ')');
  w('');
  w(SKIP[g].why);
  w('');
  w(SKIP[g].fams.map(f => '`' + f + '`').join(', '));
  w('');
}

/* ---------- what still needs work ---------- */
const bad = audit.filter(r => r.verdict !== 'OK' && r.verdict !== 'THIN');
w('## Still imperfect — ' + bad.length + ' props');
w('');
w('Kept rather than dropped: each is a background prop whose failure mode is "reads as');
w('one flat colour" or "invisible edge-on", not "breaks the scene".');
w('');
if (bad.length) {
  w('| prop | pack | verdict | note |');
  w('|---|---|---|---|');
  for (const r of bad.sort((a, b2) => a.name.localeCompare(b2.name))) {
    w('| `' + r.name + '` | ' + r.pack + ' | ' + r.verdict + ' | ' + (r.note || '') + ' |');
  }
  w('');
}

w('## How to change any of this');
w('');
w('```');
w('node tools/scene-manifest.js           # what resolves, what collides, what is missing');
w('node tools/scene-manifest.js --audit   # the SKIP tally');
w('node tools/scene-manifest.js --stage   # copy chosen FBX to tools/_fbx/');
w('node tools/fbx2glb.js                  # convert, normalise size, decimate');
w('node tools/prop-audit.js               # render every prop and verify');
w('node tools/make-asset-doc.js           # regenerate this file');
w('```');
w('');
w('To promote something out of SKIP: move the family into a bucket in');
w('`tools/scene-manifest.js`, then re-run the five commands above. The audit will tell');
w('you immediately whether it renders.');
w('');
w('One thing to know before adding anything: **`tools/_convert.html` holds a `SIZE`');
w('table of real-world heights per family.** These six packs disagree about authoring');
w('units by five orders of magnitude — `Mountain_1A` is 20,000 units and `Coconut_01A`');
w('is 0.30 — so a new family without a `SIZE` entry falls back to 1 metre and will look');
w('wrong. Add the height, not a scale factor.');

const out = path.join(__dirname, '..', 'docs', 'asset-audit.md');
fs.writeFileSync(out, L.join(NL) + NL);
console.log('wrote docs/asset-audit.md — ' + L.length + ' lines');
console.log('  MUST ' + buckets.MUST.length + ' families, NICE ' + buckets.NICE.length
  + ', OK ' + buckets.OK.length + ', SKIP ' + skipN);
console.log('  render: ' + okTotal + '/' + audit.length + ' (' + Math.round(okTotal / audit.length * 100) + '%)');
